export function pickRandomPrefix(random = Math.random, excluded = '') {
  const candidates = TITLE_PREFIXES.filter((prefix) => prefix !== excluded);
  return candidates[Math.floor(random() * candidates.length)];
}

export function formatPlayerName(name, prefix) {
  const trimmedName = name.trim();
  return trimmedName ? `${prefix} ${trimmedName}`.trim() : '';
}
